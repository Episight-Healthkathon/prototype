"""Exports the API contract for the frontend (BE-1.4, BE-1.11, BE-7.7).

Writes packages/shared-types/openapi.json, src/index.ts and deterministic mock fixtures generated by the real
system on the interim dataset: screening output (queue, case detail, timeline) and, for every case, a real
investigation run (mid-run and completed InvestigationView, evidence list, evidence details, brief).

Investigation fixtures use FULL_RULE_PLANNER, a fixed timestamp and a counting clock, so they are byte-stable
and `git diff` shows only real behavior changes.
"""

import itertools
import json
from collections import defaultdict
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from episight.agent.context import CaseContext
from episight.agent.loading import contexts_from_dataset
from episight.agent.orchestrator import run_investigation
from episight.agent.planners.rule_planner import RulePlanner
from episight.api import views
from episight.contracts.api import (
    CaseList,
    CaseState,
    Evidence,
    EvidenceDetail,
    EvidenceList,
    EvidenceSource,
    InvestigationAction,
    InvestigationView,
    RunSummary,
    TextHighlight,
)
from episight.contracts.enums import InvestigationMode, RunStatus, SourceType
from episight.db.models import ProviderRow
from episight.episodes.timeline import build_timeline
from episight.ingest.loader import load_dataset, load_policies
from episight.ingest.seed import case_row
from episight.screening.rules import screen

FIXED_NOW = datetime.fromisoformat("2026-10-02T09:00:00+07:00")
FIXTURE_MODE = InvestigationMode.FULL_RULE_PLANNER


def _dump(path: Path, payload: Any) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(payload, BaseModel):
        payload = payload.model_dump(mode="json", by_alias=True)
    path.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=False) + "\n", encoding="utf-8", newline="\n"
    )
    return path


def _write_ts_aliases(path: Path, spec: dict) -> Path:
    """Named TS aliases over openapi-typescript's output (src/api.d.ts, produced by `pnpm generate`)."""
    lines = [
        "// GENERATED by `uv run episight export-contract`. Do not edit by hand.",
        "// Named aliases for the API Contract v1 schemas in ./api.d.ts (run `pnpm generate` to refresh it).",
        'import type { components, paths } from "./api";',
        "",
        "export type { components, paths };",
        'export type Schemas = components["schemas"];',
        "",
        *(f'export type {n} = components["schemas"]["{n}"];' for n in sorted(spec["components"]["schemas"])),
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return path


class _SnapshotRecorder:
    """Keeps the API view after every step, so a mid-run snapshot can be exported."""

    def __init__(self) -> None:
        self.snapshots: list[tuple[CaseState, list[InvestigationAction]]] = []

    def on_state(self, st, ctx) -> None: ...

    def on_step(self, st, ctx, action, new_evidence, decision) -> None:
        self.snapshots.append((st.to_case_state(ctx), list(st.trail)))

    def on_finish(self, st, ctx, brief, validation) -> None: ...


def _evidence_source(ctx: CaseContext, ev: Evidence) -> EvidenceSource:
    base = {"source_type": ev.source_type, "source_id": ev.source_id, "title": ev.source_title}
    highlight = TextHighlight(char_start=ev.char_start, char_end=ev.char_end) if ev.char_start is not None else None
    if ev.source_type == SourceType.CLINICAL_NOTE:
        note = ctx.notes[ev.source_id]
        return EvidenceSource(**base, text=note.text, highlight=highlight, availability=note.availability)
    if ev.source_type == SourceType.POLICY_SECTION:
        s = ctx.policy.get(ev.source_id)
        return EvidenceSource(
            **base,
            text=s.text,
            highlight=highlight,
            document_title=s.document_title,
            section=s.section,
            version=s.version,
            effective_date=s.effective_date,
            source_ref=s.source_ref,
            source_url=s.source_url,
        )
    record = {SourceType.EPISODE_RECORD: ctx.episodes, SourceType.PROVIDER_RECORD: ctx.providers}.get(
        ev.source_type, {}
    ).get(ev.source_id)
    value = None
    if record is not None and ev.field_path:
        value = getattr(record, ev.field_path.rsplit(".", 1)[-1], None)
        if isinstance(value, list):
            value = [v.model_dump(mode="json") if isinstance(v, BaseModel) else v for v in value]
        elif hasattr(value, "value"):
            value = value.value
    return EvidenceSource(**base, field_path=ev.field_path, value=value)


def _investigation_fixtures(ctx: CaseContext) -> list[tuple[str, BaseModel]]:
    counter = itertools.count()
    recorder = _SnapshotRecorder()
    run_id = "RUN-FIXTURE-" + ctx.case_id.removeprefix("CASE-")
    result = run_investigation(
        ctx,
        run_id=run_id,
        planner=RulePlanner(),
        mode=FIXTURE_MODE,
        recorder=recorder,
        clock=lambda: next(counter) * 0.001,
        now=lambda: FIXED_NOW,
    )
    st = result.state
    finished = FIXED_NOW + timedelta(seconds=st.step)
    completed = InvestigationView(
        run=RunSummary(
            run_id=run_id,
            mode=FIXTURE_MODE,
            run_status=RunStatus.COMPLETED,
            step=st.step,
            max_steps=st.max_steps,
            started_at=FIXED_NOW,
            finished_at=finished,
            outcome=st.outcome,
            stop_reason=st.stop_reason,
        ),
        state=st.to_case_state(ctx),
        trail=st.trail,
    )
    mid_state, mid_trail = recorder.snapshots[max(0, len(recorder.snapshots) // 2 - 1)]
    running = InvestigationView(
        run=RunSummary(
            run_id=run_id,
            mode=FIXTURE_MODE,
            run_status=RunStatus.RUNNING,
            step=mid_state.investigation_step,
            max_steps=st.max_steps,
            started_at=FIXED_NOW,
            finished_at=None,
            outcome=None,
            stop_reason=None,
        ),
        state=mid_state,
        trail=mid_trail,
    )
    evidence = sorted(st.evidence.values(), key=lambda e: (e.investigation_step, e.evidence_id))
    base = f"cases/{ctx.case_id}"
    out: list[tuple[str, BaseModel]] = [
        (f"{base}.investigation.running.json", running),
        (f"{base}.investigation.completed.json", completed),
        (f"{base}.evidence.json", EvidenceList(items=evidence, total=len(evidence), limit=200, offset=0)),
        (f"{base}.brief.json", result.brief),
    ]
    out += [
        (f"evidence/{e.evidence_id}.json", EvidenceDetail(**e.model_dump(), source=_evidence_source(ctx, e)))
        for e in evidence
    ]
    return out


def export(out: Path, dataset_dir: Path, policy_dir: Path | None = None) -> list[Path]:
    from episight.main import create_app

    spec = create_app().openapi()
    written = [_dump(out / "openapi.json", spec), _write_ts_aliases(out / "src" / "index.ts", spec)]
    dataset = load_dataset(dataset_dir)
    policies = load_policies(policy_dir) if policy_dir else None
    contexts = {c.case_id: c for c in contexts_from_dataset(dataset, policies)}
    cases = sorted(screen(dataset.episodes).cases, key=lambda c: c.index_date, reverse=True)
    providers = {p.provider_id: p for p in dataset.providers}
    provider_rows = {
        p.provider_id: ProviderRow(
            provider_id=p.provider_id,
            name=p.name,
            provider_type=p.provider_type.value,
            hospital_class=p.hospital_class,
            region=p.region,
        )
        for p in dataset.providers
    }
    claims = {c.episode_id: c for c in dataset.claims}
    notes: dict[str, list] = defaultdict(list)
    for n in dataset.notes:
        notes[n.episode_id].append(n)

    fixtures = out / "fixtures"
    rows, index_cases = [], {}
    for case in cases:
        row = case_row(case)
        row.updated_at = FIXED_NOW
        rows.append(row)
        base = f"cases/{case.case_id}"
        written.append(
            _dump(
                fixtures / f"{base}.detail.json", views.case_detail(row, provider_rows[case.provider_id], None, False)
            )
        )
        timeline = build_timeline(
            case_id=case.case_id,
            patient_id=case.patient_id,
            episode_group_ids=case.episode_group_ids,
            threshold_days=case.rule.threshold_days,
            patient_episodes=[e for e in dataset.episodes if e.patient_id == case.patient_id],
            providers=providers,
            claims_by_episode=claims,
            notes_by_episode=notes,
        )
        written.append(_dump(fixtures / f"{base}.episodes.json", timeline))
        investigation = _investigation_fixtures(contexts[case.case_id])
        for name, model in investigation:
            written.append(_dump(fixtures / name, model))
        index_cases[case.case_id] = {
            "detail": f"{base}.detail.json",
            "episodes": f"{base}.episodes.json",
            "investigation_running": f"{base}.investigation.running.json",
            "investigation_completed": f"{base}.investigation.completed.json",
            "evidence": f"{base}.evidence.json",
            "brief": f"{base}.brief.json",
            "evidence_details": [n for n, _ in investigation if n.startswith("evidence/")],
        }
    written.append(
        _dump(
            fixtures / "cases.list.json",
            CaseList(
                items=[views.case_summary(r, provider_rows[r.provider_id]) for r in rows],
                total=len(rows),
                limit=50,
                offset=0,
            ),
        )
    )
    written.append(
        _dump(
            fixtures / "index.json",
            {
                "contract_version": "1",
                "dataset_version": dataset.manifest.dataset_version,
                "corpus_version": policies.manifest.corpus_version if policies else None,
                "generated_by": "uv run episight export-contract (apps/api)",
                "investigation_mode": FIXTURE_MODE.value,
                "note": "Detail and episodes show cases before investigation (FLAGGED). Investigation, evidence and brief "
                "files are real engine output on the interim dataset.",
                "cases_list": "cases.list.json",
                "cases": index_cases,
            },
        )
    )
    return written
